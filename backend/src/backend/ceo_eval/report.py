"""Markdown rendering of a run record. Reports measurements only — no pass/fail verdicts and no thresholds (spec §6.18)."""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any


def _pct(r: Mapping[str, Any] | None) -> str:
    if not r or r.get("pct") is None:
        return "n/a"
    return f"{r['pct']}% ({r['n']}/{r['of']})"


def _st(s: Mapping[str, Any] | None, key: str = "p50") -> str:
    if not s or not s.get("n"):
        return "-"
    return f"{s[key]:.0f}" if isinstance(s[key], (int, float)) else str(s[key])


def _lat_row(label: str, s: Mapping[str, Any]) -> str:
    if not s or not s.get("n"):
        return f"| {label} | 0 | - | - | - | - |"
    return f"| {label} | {s['n']} | {s['min']:.0f} | {s['p50']:.0f} | {s['p95']:.0f} | {s['max']:.0f} |"


def render(rec: Mapping[str, Any]) -> str:
    models: Mapping[str, Any] = rec["models"]
    L: list[str] = []
    L.append(f"# CEO classifier/composer evaluation — baseline run `{rec['run_id']}`\n")
    L.append("*Generated by `python -m backend.ceo_eval report`; do not edit by hand. Measurements only: **no pass/fail threshold is set** "
             "(spec §6.18 — thresholds are a human decision after this run).*\n")
    env = rec.get("environment", {})
    L.append("## Run provenance\n")
    L.append(f"- Host: {env.get('processor')} · {env.get('logical_cpus')} logical CPUs · **CPU-only inference** · {env.get('os')}")
    L.append(f"- Ollama {env.get('ollama_version')}; classifier prompt `{rec.get('classifier_prompt_version')}`, composer prompt `{rec.get('composer_prompt_version')}`")
    for f, d in rec.get("fixtures", {}).items():
        L.append(f"- Fixture `{f}` sha256:{d['sha256_16']} — {d['cases']} cases" + (f" ({d['scored']} scored, {d['pending']} pending/excluded)" if "scored" in d else ""))
    a = rec.get("args", {})
    L.append(f"- Settings: thinking `{a.get('think')}`, num_ctx {a.get('num_ctx')}, temperature 0, seed 0, classifier decoding {'unconstrained' if a.get('unconstrained') else 'schema-constrained'}, "
             f"limits: classifier {a.get('classifier_limit') or 'all'}, composer {a.get('composer_limit') or 'all'}")
    L.append("")

    L.append("## 1. Classifier — accuracy and safety (effective = after code enforces the closed catalog and required slots)\n")
    names = list(models)
    L.append("| Measure | " + " | ".join(names) + " |")
    L.append("|---|" + "---|" * len(names))
    keys = [
        ("case_pass", "Whole case correct (route+key+slots+needs+clarify target, nothing forbidden)"),
        ("route_accuracy_effective", "Route accuracy — effective"),
        ("route_accuracy_raw_model", "Route accuracy — raw model verdict"),
        ("key_accuracy", "Route-key accuracy (executing routes)"),
        ("slot_accuracy", "Slot accuracy (cases with required slots)"),
        ("needs_agent_accuracy", "Absent-agent identification (`needs_agent`)"),
        ("clarify_target_accuracy", "Clarify asks about the right thing"),
        ("guess_rate_when_should_clarify", "**Guess rate** — executed when it should have clarified"),
        ("over_clarify_rate_when_should_execute", "Over-clarify rate — asked when it should have executed"),
        ("over_routing_to_metered_on_traps", "**Over-routing to metered** on traps"),
        ("forbidden_execution_rate", "**Forbidden execution** (injection / writes) "),
        ("parse_failures", "Unparseable output"),
        ("out_of_catalog_keys", "Out-of-catalog keys (rejected by code)"),
        ("missing_required_slot_rescued_by_code", "Missing required slot caught by code (model guessed to execute)"),
    ]
    for k, label in keys:
        L.append(f"| {label} | " + " | ".join(_pct(models[m].get("classifier", {}).get("summary", {}).get(k)) for m in names) + " |")
    L.append("")
    cats = sorted({c for m in names for c in models[m].get("classifier", {}).get("summary", {}).get("by_category", {})})
    if cats:
        L.append("**Whole-case correctness by category**\n")
        L.append("| Category | " + " | ".join(names) + " |")
        L.append("|---|" + "---|" * len(names))
        for c in cats:
            L.append(f"| {c} | " + " | ".join(_pct(models[m].get("classifier", {}).get("summary", {}).get("by_category", {}).get(c)) for m in names) + " |")
        L.append("")
    for m in names:
        cl = models[m].get("classifier")
        if not cl:
            continue
        L.append(f"**Confusion (expected → predicted effective route), `{m}`**\n")
        for exp, row in cl["summary"]["confusion_expected_to_predicted"].items():
            L.append(f"- {exp}: " + ", ".join(f"{p} ×{n}" for p, n in sorted(row.items(), key=lambda kv: -kv[1])))
        L.append("")
        misses = [r for r in cl["results"] if not r["ok"]]
        L.append(f"<details><summary>`{m}` — {len(misses)} missed classifier cases (id · expected→predicted · key · slots)</summary>\n")
        for r in misses:
            L.append(f"- `{r['case_id']}` ({r['category']}/{r['scenario']}) → {r['predicted_route']} {r['predicted_key'] or ''} {r['predicted_slots'] or ''} flags={r['verdict_flags'] or ''}")
        L.append("\n</details>\n")

    L.append("## 2. Composer — numeral safety, placeholders, disclaimers, non-results\n")
    L.append("| Measure | " + " | ".join(names) + " |")
    L.append("|---|" + "---|" * len(names))
    ckeys = [
        ("case_pass", "Whole case clean (gate + all case rules)"),
        ("gate_fail_would_fall_back_to_template", "**Draft fails the gate → would fall back to TEMPLATE_FALLBACK**"),
        ("numeral_gate_violation_rate", "**Numeral in model prose** (any kind)"),
        ("numeral_violations_that_are_date_like_only", "…of which date-like only (strictness question, Q13)"),
        ("unknown_token_rate", "Unknown placeholder token"),
        ("unavailable_figure_presented_as_value", "UNAVAILABLE figure used as a value"),
        ("required_disclaimer_or_verbatim_dropped", "**Required disclaimer / verbatim marker dropped**"),
        ("named_gap_or_attach_control_dropped", "Named gap / Add-agent control dropped"),
        ("non_result_narrated_as_real", "**Non-result narrated as a real result**"),
        ("injection_obeyed", "**Injection in evidence obeyed** (or numeral emitted)"),
        ("advisory_numeric_benchmark_leak", "Advisory answer containing a numeral (benchmark leak)"),
    ]
    for k, label in ckeys:
        L.append(f"| {label} | " + " | ".join(_pct(models[m].get("composer", {}).get("summary", {}).get(k)) for m in names) + " |")
    L.append("")
    ccats = sorted({c for m in names for c in models[m].get("composer", {}).get("summary", {}).get("by_category", {})})
    if ccats:
        L.append("**Whole-case clean by category**\n")
        L.append("| Category | " + " | ".join(names) + " |")
        L.append("|---|" + "---|" * len(names))
        for c in ccats:
            L.append(f"| {c} | " + " | ".join(_pct(models[m].get("composer", {}).get("summary", {}).get("by_category", {}).get(c)) for m in names) + " |")
        L.append("")
    for m in names:
        co = models[m].get("composer")
        if not co:
            continue
        L.append(f"`{m}` violation codes: {co['summary']['violation_codes'] or 'none'}; case-rule violations: {co['summary']['case_violation_kinds'] or 'none'}; median words {co['summary']['median_words']}\n")

    L.append("## 3. Latency — per stage (milliseconds, wall clock)\n")
    L.append("### 3a. Model stages (local Ollama, CPU only)\n")
    L.append("| Model · stage | n | min | p50 | p95 | max |")
    L.append("|---|---|---|---|---|---|")
    for m in names:
        for suite, label in (("classifier", "classify"), ("composer", "compose")):
            lat = models[m].get(suite, {}).get("latency")
            if not lat:
                continue
            L.append(_lat_row(f"`{m}` {label} — total", lat["wall_ms"]))
            L.append(_lat_row(f"`{m}` {label} — time to first answer token", lat["ttft_ms"]))
            L.append(_lat_row(f"`{m}` {label} — prompt tokens, total (tokens)", lat["prompt_tokens_total"]))
            L.append(_lat_row(f"`{m}` {label} — output tokens (tokens)", lat["output_tokens"]))
    L.append("")
    L.append("### 3b. Cold start and prefix-cache probe (classifier prefix)\n")
    L.append("| Model | Probe | wall | load | prompt tokens (total) | prompt eval | output tokens | eval |")
    L.append("|---|---|---|---|---|---|---|---|")
    for m in names:
        pr = models[m].get("cold_and_cache_probe")
        if not pr:
            continue
        for row in pr["probes"]:
            L.append(f"| `{m}` | {row['probe']} | {row['wall_ms']} | {row['load_ms']} | {row['prompt_tokens_total']} | {row['prompt_eval_ms']} | {row['output_tokens']} | {row['eval_ms']} |")
        L.append(f"| `{m}` | *(static prefix is {pr['static_prefix_chars']} characters)* | | | | | | |")
    L.append("")
    db = rec.get("db_latency")
    if db:
        L.append("### 3c. Deterministic stages — real Postgres, real code, `metrion_app` role\n")
        L.append(f"Database: `{db['database']}` (scratch, same host as the model server) · seed: {db['seed']} · {db['repeat']} repetitions after one warm-up · leg statuses observed: {db.get('leg_statuses')}\n")
        L.append("| Stage | n | min | p50 | p95 | max |")
        L.append("|---|---|---|---|---|---|")
        for stage, s in db["stages"].items():
            L.append(_lat_row(stage, s))
        L.append("")
    return "\n".join(L) + "\n"
