"""Trusted-domain allowlist — C4/D7. Hardcoded, not configurable per tenant.

This check runs before any fetcher call anywhere in this package (see `service.py`). It is
deliberately the first thing evaluated in the capture pipeline: a non-allowlisted URL never
reaches a `Fetcher`, real or fake, which is also what makes it possible to assert in tests
that a rejected URL never triggers network I/O.

D7 ("should the allowlist also accept short-link domains?") is now resolved: `amzn.in`
(Amazon's own official short-link domain, generated by its mobile app's Share button) and
`fkrt.co` (Flipkart's equivalent) are accepted alongside the three canonical domains — real
sellers routinely copy these, and rejecting them was pure friction, not a security boundary
(nothing is ever fetched either way, C4). Meesho has no comparably widespread official
short-link domain, so none is added for it; this can be revisited if that changes.

`_HOST_TO_MARKETPLACE` is the single source of truth for both "is this host trusted" and
"which Marketplace does this host mean" — `backend/api/v1/ci.py` used to duplicate the
host-to-marketplace mapping with its own separate list, which is exactly the kind of drift
that made the allowlist and the marketplace-derivation logic disagree; it now imports
`marketplace_for_host` from here instead.
"""

from __future__ import annotations

from urllib.parse import urlsplit

from competitor_intelligence.types import Marketplace

_HOST_TO_MARKETPLACE: dict[str, Marketplace] = {
    "amazon.in": Marketplace.AMAZON,
    "amzn.in": Marketplace.AMAZON,
    "flipkart.com": Marketplace.FLIPKART,
    "fkrt.co": Marketplace.FLIPKART,
    "meesho.com": Marketplace.MEESHO,
}

ALLOWED_HOSTS: frozenset[str] = frozenset(_HOST_TO_MARKETPLACE)


def _matching_allowed_host(host: str) -> str | None:
    host = host.lower()
    for allowed in _HOST_TO_MARKETPLACE:
        if host == allowed or host.endswith(f".{allowed}"):
            return allowed
    return None


def is_allowed_host(url: str) -> bool:
    """True if `url`'s host is one of ALLOWED_HOSTS or a subdomain of one (e.g.
    `www.amazon.in`, `m.flipkart.com`). Anything else — a different TLD, a look-alike
    domain, a redirect target outside the allowlist — is rejected."""
    host = urlsplit(url).hostname
    if not host:
        return False
    return _matching_allowed_host(host) is not None


def marketplace_for_host(url: str) -> Marketplace | None:
    """The `Marketplace` a trusted host maps to, or `None` if `url`'s host isn't allowed —
    callers that need a 400/refusal message on `None` (e.g. the API layer) still own that
    presentation choice; this function only ever classifies, never raises."""
    host = urlsplit(url).hostname
    if not host:
        return None
    allowed = _matching_allowed_host(host)
    return _HOST_TO_MARKETPLACE[allowed] if allowed else None
